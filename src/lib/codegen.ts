import type { Settings } from "./tokens";

/** Sample React Button wired to the generated CSS variables. */
export function generateReactSample(s: Settings): string {
  return `// Generated by Design System Playground
// primary ${s.primary} · neutral ${s.neutral} · radius ${s.radius}px · base ${s.fontSize}px · ${s.density}
// Requires the CSS variables from the CSS panel to be loaded on :root.
import { useState, type ButtonHTMLAttributes, type CSSProperties } from "react";

type Variant = "primary" | "secondary" | "ghost" | "danger";
type Size = "sm" | "md" | "lg";

interface ButtonProps extends ButtonHTMLAttributes<HTMLButtonElement> {
  variant?: Variant;
  size?: Size;
}

const palette: Record<Variant, { bg: string; hover: string; fg: string; border: string }> = {
  primary: { bg: "var(--primary)", hover: "var(--primary-hover)", fg: "var(--primary-fg)", border: "transparent" },
  secondary: { bg: "var(--surface)", hover: "var(--surface-muted)", fg: "var(--text)", border: "var(--border-strong)" },
  ghost: { bg: "transparent", hover: "var(--surface-muted)", fg: "var(--text)", border: "transparent" },
  danger: { bg: "var(--danger)", hover: "var(--danger-hover)", fg: "var(--danger-fg)", border: "transparent" },
};

const sizes: Record<Size, { padding: string; fontSize: string }> = {
  sm: { padding: "calc(var(--space-1) * var(--density)) calc(var(--space-3) * var(--density))", fontSize: "var(--font-size-sm)" },
  md: { padding: "calc(var(--space-2) * var(--density)) calc(var(--space-4) * var(--density))", fontSize: "var(--font-size-base)" },
  lg: { padding: "calc(var(--space-3) * var(--density)) calc(var(--space-5) * var(--density))", fontSize: "var(--font-size-lg)" },
};

export function Button({ variant = "primary", size = "md", disabled, style, ...props }: ButtonProps) {
  const [hovered, setHovered] = useState(false);
  const colors = palette[variant];
  const dims = sizes[size];

  const css: CSSProperties = {
    background: hovered && !disabled ? colors.hover : colors.bg,
    color: colors.fg,
    border: "1px solid " + colors.border,
    borderRadius: "var(--radius-md)",
    padding: dims.padding,
    fontSize: dims.fontSize,
    fontWeight: 600,
    cursor: disabled ? "not-allowed" : "pointer",
    opacity: disabled ? 0.5 : 1,
    ...style,
  };

  return (
    <button
      type="button"
      disabled={disabled}
      style={css}
      onMouseEnter={() => setHovered(true)}
      onMouseLeave={() => setHovered(false)}
      {...props}
    />
  );
}
`;
}
